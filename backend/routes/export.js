const router = require('express').Router();
const { authMiddleware } = require('../middleware/auth');
const { detectSecrets } = require('../utils/sanitize');

// ─── BUG-010 fix: Input validation helpers ────────────────────────────────────
// All user-supplied values are validated against strict allowlists before being
// embedded into YAML/Markdown output. This prevents YAML injection and CI step
// injection via crafted newline sequences in fields like awsRegion or tfVersion.

const TF_VERSION_RE  = /^\d+\.\d+\.\d+$/;
const AWS_REGION_RE  = /^[a-z]{2}-[a-z]+-\d+$/;
const ROLE_ARN_RE    = /^(arn:aws:iam::\d{12}:role\/[\w+=,.@/-]+)?$/;
const WORKING_DIR_RE = /^[a-zA-Z0-9_./-]{1,200}$/;
// Free-text fields: strip characters that are structurally significant in YAML
// (newlines, colons at start-of-value, leading/trailing whitespace, backticks)
function sanitizeFreeText(str, maxLen = 200) {
  if (typeof str !== 'string') return '';
  return str
    .replace(/[\r\n]/g, ' ')   // no newlines — would break YAML/Markdown structure
    .replace(/`/g, "'")        // no backticks — can break Markdown fenced blocks
    .trim()
    .slice(0, maxLen);
}

function validateExportInputs(fields, res) {
  const { tfVersion, awsRegion, roleArn, workingDir } = fields;

  if (tfVersion !== undefined && !TF_VERSION_RE.test(tfVersion)) {
    res.status(400).json({ error: 'tfVersion must be a semantic version (e.g. 1.7.0)' });
    return false;
  }
  if (awsRegion !== undefined && !AWS_REGION_RE.test(awsRegion)) {
    res.status(400).json({ error: 'awsRegion must be a valid AWS region code (e.g. us-east-1)' });
    return false;
  }
  if (roleArn !== undefined && !ROLE_ARN_RE.test(roleArn || '')) {
    res.status(400).json({ error: 'roleArn must be a valid IAM role ARN or empty' });
    return false;
  }
  if (workingDir !== undefined && !WORKING_DIR_RE.test(workingDir || '.')) {
    res.status(400).json({ error: 'workingDir must be a simple relative path' });
    return false;
  }
  return true;
}

// ─── GitHub Actions ───────────────────────────────────────────────────────────
router.post('/pipeline/github-actions', authMiddleware, (req, res) => {
  const {
    projectName  = 'my-terraform-project',
    tfVersion    = '1.7.0',
    awsRegion    = 'us-east-1',
    roleArn      = '',
    enableApply  = false,
    workingDir   = '.',
  } = req.body;

  if (!validateExportInputs({ tfVersion, awsRegion, roleArn, workingDir }, res)) return;

  // Sanitize free-text fields before embedding in YAML
  const safeProjectName = sanitizeFreeText(projectName);
  const safeRoleArn     = roleArn || 'arn:aws:iam::ACCOUNT_ID:role/TFGenGitHubActionsRole';

  const yaml = `# GitHub Actions — Terraform CI/CD Pipeline
# Generated by TFGen on ${new Date().toISOString().split('T')[0]}
# Project: ${safeProjectName}

name: Terraform

on:
  push:
    branches: [main]
  pull_request:
    branches: [main]

permissions:
  id-token: write   # Required for OIDC
  contents: read
  pull-requests: write

env:
  TF_VERSION: "${tfVersion}"
  AWS_REGION: "${awsRegion}"
  WORKING_DIR: "${workingDir}"

jobs:
  terraform:
    name: Terraform Plan & Apply
    runs-on: ubuntu-latest
    defaults:
      run:
        working-directory: \${{ env.WORKING_DIR }}

    steps:
      - name: Checkout code
        uses: actions/checkout@v4

      - name: Configure AWS credentials (OIDC)
        uses: aws-actions/configure-aws-credentials@v4
        with:
          role-to-assume: "${safeRoleArn}"
          aws-region: \${{ env.AWS_REGION }}

      - name: Setup Terraform
        uses: hashicorp/setup-terraform@v3
        with:
          terraform_version: \${{ env.TF_VERSION }}

      - name: Terraform Format Check
        id: fmt
        run: terraform fmt -check -recursive
        continue-on-error: true

      - name: Terraform Init
        id: init
        run: terraform init -backend=false

      - name: Terraform Validate
        id: validate
        run: terraform validate -no-color

      - name: Run Checkov Security Scan
        uses: bridgecrewio/checkov-action@v12
        with:
          directory: \${{ env.WORKING_DIR }}
          framework: terraform
          soft_fail: false
          output_format: sarif
          output_file_path: checkov-results.sarif

      - name: Upload Checkov SARIF results
        uses: github/codeql-action/upload-sarif@v3
        if: always()
        with:
          sarif_file: checkov-results.sarif

      - name: Terraform Plan
        id: plan
        if: github.event_name == 'pull_request'
        run: terraform plan -no-color -input=false
        continue-on-error: true

      - name: Comment Plan on PR
        uses: actions/github-script@v7
        if: github.event_name == 'pull_request'
        with:
          script: |
            const output = \`#### Terraform Format: \\\`\${{ steps.fmt.outcome }}\\\`
            #### Terraform Validate: \\\`\${{ steps.validate.outcome }}\\\`
            #### Terraform Plan: \\\`\${{ steps.plan.outcome }}\\\`

            <details><summary>Show Plan</summary>

            \\\`\\\`\\\`terraform
            \${{ steps.plan.outputs.stdout }}
            \\\`\\\`\\\`

            </details>

            *Triggered by @\${{ github.actor }}, Action: \\\`\${{ github.event_name }}\\\`*\`;
            github.rest.issues.createComment({
              issue_number: context.issue.number,
              owner: context.repo.owner,
              repo: context.repo.repo,
              body: output
            })
${enableApply ? `
      - name: Terraform Apply
        if: github.ref == 'refs/heads/main' && github.event_name == 'push'
        run: terraform apply -auto-approve -input=false
` : `      # Apply is disabled. Enable it by setting enableApply=true in TFGen export settings.
      # - name: Terraform Apply
      #   if: github.ref == 'refs/heads/main' && github.event_name == 'push'
      #   run: terraform apply -auto-approve -input=false
`}`;

  res.json({ filename: '.github/workflows/terraform.yml', content: yaml });
});

// ─── GitLab CI ────────────────────────────────────────────────────────────────
router.post('/pipeline/gitlab-ci', authMiddleware, (req, res) => {
  const { tfVersion = '1.7.0', awsRegion = 'us-east-1', enableApply = false } = req.body;

  if (!validateExportInputs({ tfVersion, awsRegion }, res)) return;

  const yaml = `# GitLab CI — Terraform Pipeline
# Generated by TFGen on ${new Date().toISOString().split('T')[0]}

image:
  name: hashicorp/terraform:${tfVersion}
  entrypoint: [""]

variables:
  AWS_DEFAULT_REGION: "${awsRegion}"
  TF_IN_AUTOMATION: "true"

stages:
  - validate
  - security
  - plan
${enableApply ? '  - apply' : '  # - apply  # Uncomment to enable apply stage'}

cache:
  paths:
    - .terraform/

before_script:
  - terraform init -backend=false

fmt:
  stage: validate
  script: terraform fmt -check -recursive

validate:
  stage: validate
  script: terraform validate -no-color

checkov:
  stage: security
  image: bridgecrew/checkov:latest
  script:
    - checkov --directory . --framework terraform --output junitxml > checkov.xml
  artifacts:
    reports:
      junit: checkov.xml

plan:
  stage: plan
  script:
    - terraform plan -no-color -input=false -out=tfplan
  artifacts:
    paths:
      - tfplan
  only:
    - merge_requests
    - main
${enableApply ? `
apply:
  stage: apply
  script:
    - terraform apply -input=false tfplan
  dependencies:
    - plan
  when: manual
  only:
    - main
` : ''}`;

  res.json({ filename: '.gitlab-ci.yml', content: yaml });
});

// ─── README ───────────────────────────────────────────────────────────────────
router.post('/readme', authMiddleware, (req, res) => {
  const {
    projectName   = 'Terraform Project',
    description   = '',
    awsRegion     = 'us-east-1',
    environment   = 'dev',
    resources     = [],
    costEstimate  = null,
  } = req.body;

  if (!validateExportInputs({ awsRegion }, res)) return;

  // Sanitize free-text fields before embedding in Markdown
  const safeProjectName = sanitizeFreeText(projectName, 100);
  const safeDescription = sanitizeFreeText(description, 500);
  const safeEnvironment = sanitizeFreeText(environment, 50);

  const resourceTable = resources.map(r =>
    `| \`${sanitizeFreeText(r.service_type || r.label, 60)}\` | ${sanitizeFreeText(r.resource_name || r.config?.name || r.label || '-', 60)} | ${r.is_module ? 'Module' : 'Resource'} |`
  ).join('\n');

  const readme = `# ${safeProjectName}

> ${safeDescription || 'Terraform infrastructure for AWS — generated by TFGen.'}

## Infrastructure Summary

| Category | Detail |
|----------|--------|
| **AWS Region** | \`${awsRegion}\` |
| **Environment** | \`${safeEnvironment}\` |
| **Resources** | ${resources.length} |
${costEstimate != null ? `| **Estimated Cost** | ~$${costEstimate}/month |` : ''}

## Resources

| Type | Name | Mode |
|------|------|------|
${resourceTable || '| — | — | — |'}

## Prerequisites

- [Terraform](https://developer.hashicorp.com/terraform/install) ≥ 1.5
- [AWS CLI](https://aws.amazon.com/cli/) configured with appropriate permissions
- S3 bucket + DynamoDB table for remote state (if using S3 backend)

## Usage

\`\`\`bash
# Initialise
terraform init

# Review plan
terraform plan

# Apply
terraform apply
\`\`\`

## Security

This configuration was scanned with [Checkov](https://www.checkov.io/).
Review the \`checkov-results.sarif\` in CI for security findings.

---
*Generated by [TFGen](https://github.com/your-org/tfgen) on ${new Date().toISOString().split('T')[0]}*
`;

  res.json({ filename: 'README.md', content: readme });
});

