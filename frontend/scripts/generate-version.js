#!/usr/bin/env node
/**
 * Regenerates src/version.js from the VERSION file (single source of
 * truth for the UI's displayed app version).
 *
 * Run automatically by the Dockerfile during `docker build` — no
 * REACT_APP_* env var or --build-arg needed at build or run time; bump
 * the version by editing the VERSION file only.
 *
 * Safe to run locally too: `node scripts/generate-version.js`.
 */

const fs = require('fs');
const path = require('path');

const versionFile = path.join(__dirname, '..', 'VERSION');
const outFile = path.join(__dirname, '..', 'src', 'version.js');

const version = fs.readFileSync(versionFile, 'utf8').trim();

const contents =
  '// AUTO-GENERATED by scripts/generate-version.js — do not edit by hand.\n' +
  '// Source of truth: frontend/VERSION\n' +
  'export const APP_VERSION = ' + JSON.stringify(version) + ';\n';

fs.writeFileSync(outFile, contents);
console.log(`[generate-version] APP_VERSION = ${version}`);
